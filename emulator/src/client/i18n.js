    // Resolved once per page load. A link from the publisher app carries ?culture=, so crossing
    // between the two systems keeps one language; we consume it, remember it, and strip it from
    // the URL. Leaving it in place would beat the EN/日本語 toggle on every reload.
    let langResolved = null;
    function i18nLang() {
        if (langResolved) {
            return langResolved;
        }

        const requested = new URLSearchParams(location.search).get('culture');
        if (requested === 'en' || requested === 'ja') {
            localStorage.setItem('emu-lang', requested);
            const url = new URL(location.href);
            url.searchParams.delete('culture');
            history.replaceState(null, '', url.pathname + url.search + url.hash);
            langResolved = requested;
            return langResolved;
        }

        const stored = localStorage.getItem('emu-lang');
        langResolved = (stored === 'en' || stored === 'ja')
            ? stored
            : (((navigator.language || '').toLowerCase().indexOf('ja') === 0) ? 'ja' : 'en');
        return langResolved;
    }

    function t(key) {
        const lang = i18nLang();
        return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
    }

    function formatI18n(key, values) {
        return t(key).replace(/\{([^}]+)\}/g, function (_, name) {
            return Object.prototype.hasOwnProperty.call(values, name) ? values[name] : '{' + name + '}';
        });
    }

    function applyI18n(root) {
        root = root || document;
        const $root = $(root);
        $root.find('[data-i18n]').addBack('[data-i18n]').each(function () {
            this.textContent = t(this.getAttribute('data-i18n'));
        });
        $root.find('[data-i18n-html]').addBack('[data-i18n-html]').each(function () {
            this.innerHTML = t(this.getAttribute('data-i18n-html'));
        });
        $root.find('[data-i18n-attr]').addBack('[data-i18n-attr]').each(function () {
            const el = this;
            const pairs = el.getAttribute('data-i18n-attr').split(';');
            pairs.forEach(function (pair) {
                const parts = pair.split(':');
                if (parts.length === 2) {
                    el.setAttribute(parts[0], t(parts[1]));
                }
            });
        });
    }

    function injectLanguageToggle() {
        const nav = document.querySelector('.header-language ul');
        if (!nav || nav.querySelector('li.lang')) {
            return;
        }

        const li = document.createElement('li');
        li.className = 'lang';
        li.innerHTML = '<a href="#" data-lang="en">EN</a><a href="#" data-lang="ja">日本語</a>';
        nav.appendChild(li);

        const lang = i18nLang();
        Array.prototype.forEach.call(li.querySelectorAll('a'), function (a) {
            if (a.getAttribute('data-lang') === lang) {
                a.className = 'active-lang';
            }
            a.addEventListener('click', function (e) {
                e.preventDefault();
                localStorage.setItem('emu-lang', a.getAttribute('data-lang'));
                location.reload();
            });
        });
    }

    let readyDone = false;
    function ready() {
        if (readyDone) {
            return;
        }
        readyDone = true;
        document.documentElement.lang = i18nLang();
        applyI18n(document);
        injectLanguageToggle();
    }

    window.I18N = I18N;
    window.t = t;
    window.formatI18n = formatI18n;
    window.applyI18n = applyI18n;
    window.i18nLang = i18nLang;

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', ready);
    } else {
        ready();
    }
    if (window.jQuery) {
        $(ready);
    }
